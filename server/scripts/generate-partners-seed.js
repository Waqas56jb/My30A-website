// Generates supabase/migrations/013_partners_seed.sql from scripts/data/partners.json
// (the client's "App Partners" + "Public Info" sheets). Re-runnable: the SQL is idempotent.
//   node scripts/generate-partners-seed.js
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const data = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/partners.json'), 'utf8'))
const out = path.resolve(__dirname, '../../supabase/migrations/013_partners_seed.sql')

const q = (value) => (value === null || value === undefined || value === '' ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`)
const arr = (values) => `'{${values.map((v) => `"${String(v).replace(/"/g, '\\"')}"`).join(',')}}'`
const slugify = (text) =>
  String(text)
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
const website = (value) => {
  if (!value) return null
  return /^https?:\/\//i.test(value) ? value : `https://${value}`
}

const byCategory = new Map()
for (const row of data.partners) {
  const [category] = row
  byCategory.set(category, (byCategory.get(category) || 0) + 1)
}

const lines = []
lines.push('-- Generated by server/scripts/generate-partners-seed.js — do not edit by hand.')
lines.push('-- App Partners (161, 20 categories) + Public Info free layer (79 entries, 4 sections).')
lines.push('')
lines.push('-- Placeholder vendors from 008 are retired (kept for history, hidden from guests).')
lines.push("UPDATE explore_vendors SET is_active = false WHERE kind = 'vendor' AND slug IN (")
lines.push(
  "  'bonfire-co','emerald-fire','seaside-fire','coastal-carts','beach-buggy','emerald-carts','grayton-pontoons',"
)
lines.push(
  "  'yolo-paddle','gulf-charters','sandy-lens','thirty-a-portraits','dune-studio','butterfly-bikes','big-daddys',"
)
lines.push(
  "  'rb-cycles','alys-spa','salt-yoga','gulf-glow','seaside-market','rb-boutiques','alys-shops','gulf-place-kids',"
)
lines.push("  'seacrest-minigolf','watercolor-kayak-kids');")
lines.push('')

// Guides (categories): upsert by slug so existing Figma cards keep their id/image.
lines.push('INSERT INTO explore_guides (slug, title, kind, image_url, price_from, vendor_count, place, filters, sort_order)')
lines.push('VALUES')
const guideRows = data.categories.map((c, index) => {
  const count = byCategory.get(c.category) || 0
  const vendorCount = c.slug === 'real-estate' ? 'Coming soon' : `${count} vendor${count === 1 ? '' : 's'}`
  const priceFrom = c.slug === 'real-estate' ? 'Coming soon' : 'Book direct'
  return `  (${q(c.slug)}, ${q(c.title)}, 'vendors', ${q(c.image)}, ${q(priceFrom)}, ${q(vendorCount)}, ${q(c.place)}, ${arr(c.filters)}, ${20 + index})`
})
lines.push(guideRows.join(',\n'))
lines.push('ON CONFLICT (slug) DO UPDATE SET')
lines.push('  title = EXCLUDED.title, vendor_count = EXCLUDED.vendor_count, price_from = EXCLUDED.price_from,')
lines.push('  filters = EXCLUDED.filters, place = EXCLUDED.place, is_active = true;')
lines.push('')

// Vendors
const slugFor = Object.fromEntries(data.categories.map((c) => [c.category, c.slug]))
const seen = new Set()
lines.push(
  'INSERT INTO explore_vendors (guide_slug, slug, kind, name, place, community, description, about, website_url, phone, rating, review_count, image_url, sort_order, is_active)'
)
lines.push('VALUES')
const vendorRows = data.partners.map((row, index) => {
  const [category, name, desc, area, site, phone, rating = null, reviews = null, active = true] = row
  let slug = slugify(name)
  while (seen.has(slug)) slug = `${slug}-2`
  seen.add(slug)
  const guide = data.categories.find((c) => c.category === category)
  return `  (${q(slugFor[category])}, ${q(slug)}, 'vendor', ${q(name)}, ${q(area)}, ${q(area)}, ${q(desc)}, ${q(desc)}, ${q(website(site))}, ${q(phone)}, ${rating === null ? 'NULL' : rating}, ${reviews === null ? 0 : reviews}, ${q(guide?.image || '/image6.png')}, ${index + 1}, ${active ? 'true' : 'false'})`
})
lines.push(vendorRows.join(',\n'))
lines.push('ON CONFLICT (slug) DO UPDATE SET')
lines.push('  guide_slug = EXCLUDED.guide_slug, name = EXCLUDED.name, place = EXCLUDED.place, community = EXCLUDED.community,')
lines.push('  description = EXCLUDED.description, about = EXCLUDED.about, website_url = EXCLUDED.website_url, phone = EXCLUDED.phone,')
lines.push('  rating = EXCLUDED.rating, review_count = EXCLUDED.review_count, is_active = EXCLUDED.is_active;')
lines.push('')

// Public places
lines.push('DELETE FROM public_places WHERE section_key IN (' + Object.keys(data.places).map(q).join(', ') + ');')
lines.push('INSERT INTO public_places (section_key, section_title, name, community, details, sort_order) VALUES')
const placeRows = []
for (const [key, section] of Object.entries(data.places)) {
  section.items.forEach(([name, community, details], index) => {
    placeRows.push(`  (${q(key)}, ${q(section.title)}, ${q(name)}, ${q(community)}, ${q(details)}, ${index + 1})`)
  })
}
lines.push(placeRows.join(',\n') + ';')
lines.push('')

fs.writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out}: ${data.categories.length} guides, ${data.partners.length} vendors, ${placeRows.length} public places`)
